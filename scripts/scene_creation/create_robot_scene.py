"""Create the meter-scale restaurant scene containing Nova Carter.

Run from the project root with Isaac Sim 6.0.x:

    python -u scripts/scene/create_robot_scene.py

The input restaurant must have been generated by the revised
``create_restaurant_scene.py`` and use ``1.0 m/unit``. Nova Carter is also
meter-authored, so the robot is referenced without any metric-conversion
scale. The completed stage is saved as
``scenes/generated/restaurant_robot.usda`` and left open for inspection.
"""

from __future__ import annotations

import math
import traceback
from pathlib import Path


# -----------------------------------------------------------------------------
# Project and asset configuration
# -----------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

RESTAURANT_SCENE_PATH = (
    PROJECT_ROOT
    / "scenes"
    / "generated"
    / "restaurant_base.usda"
)

OUTPUT_SCENE_PATH = (
    PROJECT_ROOT
    / "scenes"
    / "generated"
    / "restaurant_robot.usda"
)

NOVA_CARTER_ASSET = (
    "https://omniverse-content-production.s3-us-west-2.amazonaws.com/"
    "Assets/Isaac/6.0/Isaac/Robots/NVIDIA/NovaCarter/nova_carter.usd"
)

ROBOT_PRIM_PATH = "/World/Robot"

FRONT_LEFT_HAWK_CAMERA_PATH = (
    "/World/Robot/chassis_link/sensors/front_hawk/left/camera_left"
)

# GUI viewport camera only. This is independent of Nova Carter's sensors.
VIEWPORT_CAMERA_PATH = "/OmniverseKit_Persp"

# Recovered from the Perspective camera Transform panel.
INITIAL_VIEW_EYE = (4.70906, 4.53751, 2.03889)

# Look target computed from the displayed XYZ rotation
# (81.73998, 0.0, -95.11682) degrees. The target distance does not affect
# the viewing direction; ten meters gives a convenient center of interest.
INITIAL_VIEW_TARGET = (14.56589, 3.65490, 0.60223)


# -----------------------------------------------------------------------------
# Robot configuration
# -----------------------------------------------------------------------------

EXPECTED_METERS_PER_UNIT = 1.0
UNIT_TOLERANCE = 1e-9

# Recovered from the Transform panel in yesterday's placement screenshot.
# Orientation was (0, 0, 0) degrees and scale was (1, 1, 1), so only a
# translation operation is required.
ROBOT_POSITION_METERS = (12.00021, 3.94017, 0.07382)

ROBOT_VARIANTS = {
    "Physics": "physx",
    "Sensors": "All_Sensors",
    "Configuration": "No_Internals",
    "ROS": "Disabled",
}


# -----------------------------------------------------------------------------
# Stage helpers
# -----------------------------------------------------------------------------

def wait_for_stage_loading(
    simulation_app,
    stage_utils,
    *,
    max_updates: int = 1200,
    settle_updates: int = 60,
) -> int:
    """Wait for referenced assets and their variant payloads to compose."""

    updates = 0

    while (
        stage_utils.is_stage_loading()
        and updates < max_updates
        and not simulation_app.is_exiting()
    ):
        simulation_app.update()
        updates += 1

    if stage_utils.is_stage_loading():
        raise TimeoutError(
            "The USD stage is still loading after "
            f"{max_updates} application updates."
        )

    for _ in range(settle_updates):
        if simulation_app.is_exiting():
            break
        simulation_app.update()

    return updates


def open_and_validate_restaurant(
    simulation_app,
    stage_utils,
    UsdGeom,
):
    """Open the converted restaurant and require a true meter stage."""

    if not RESTAURANT_SCENE_PATH.is_file():
        raise FileNotFoundError(
            "The meter-scale restaurant scene was not found:\n"
            f"  {RESTAURANT_SCENE_PATH}\n\n"
            "Run scripts/scene/create_restaurant_scene.py first."
        )

    print(f"Opening restaurant: {RESTAURANT_SCENE_PATH}", flush=True)
    opened, stage = stage_utils.open_stage(str(RESTAURANT_SCENE_PATH))

    if not opened or stage is None:
        raise RuntimeError(
            "Isaac Sim could not open the restaurant scene:\n"
            f"  {RESTAURANT_SCENE_PATH}"
        )

    load_updates = wait_for_stage_loading(
        simulation_app,
        stage_utils,
        settle_updates=30,
    )

    meters_per_unit = float(UsdGeom.GetStageMetersPerUnit(stage))

    if not math.isclose(
        meters_per_unit,
        EXPECTED_METERS_PER_UNIT,
        rel_tol=0.0,
        abs_tol=UNIT_TOLERANCE,
    ):
        raise RuntimeError(
            "The restaurant uses the wrong stage units.\n"
            f"  Expected: {EXPECTED_METERS_PER_UNIT} m/unit\n"
            f"  Found:    {meters_per_unit} m/unit\n\n"
            "Do not add Nova Carter to the old 0.01 m/unit restaurant. "
            "Regenerate restaurant_base.usda first."
        )

    world_prim = stage.GetPrimAtPath("/World")
    environment_prim = stage.GetPrimAtPath("/World/Environment")

    if not world_prim.IsValid() or not environment_prim.IsValid():
        raise RuntimeError(
            "The restaurant stage is missing /World or /World/Environment."
        )

    if stage.GetPrimAtPath(ROBOT_PRIM_PATH).IsValid():
        raise RuntimeError(
            f"The base restaurant already contains {ROBOT_PRIM_PATH}. "
            "Use a clean restaurant_base.usda."
        )

    print(
        f"[checkpoint] Restaurant loaded in {load_updates} update(s).",
        flush=True,
    )
    print(f"[checkpoint] Stage units: {meters_per_unit} m/unit", flush=True)
    return stage


# -----------------------------------------------------------------------------
# Nova Carter composition
# -----------------------------------------------------------------------------

def select_variant(stage, set_name: str, choice: str) -> None:
    """Select one Nova Carter variant and verify the resulting choice."""

    # Variant changes may recompose the reference, so resolve the prim again
    # for every selection instead of retaining a potentially stale handle.
    robot_prim = stage.GetPrimAtPath(ROBOT_PRIM_PATH)

    if not robot_prim.IsValid():
        raise RuntimeError(
            f"Nova Carter disappeared before selecting {set_name}."
        )

    variant_set = robot_prim.GetVariantSets().GetVariantSet(set_name)
    available_choices = list(variant_set.GetVariantNames())

    if choice not in available_choices:
        raise RuntimeError(
            f"Variant {set_name}={choice!r} is unavailable. "
            f"Available choices: {available_choices}"
        )

    if not variant_set.SetVariantSelection(choice):
        raise RuntimeError(f"Could not select {set_name}={choice}.")

    selected_choice = variant_set.GetVariantSelection()

    if selected_choice != choice:
        raise RuntimeError(
            f"Variant selection did not persist: "
            f"{set_name}={selected_choice!r}."
        )

    print(
        f"  {set_name}: {selected_choice} "
        f"(available: {available_choices})",
        flush=True,
    )


def validate_robot_has_no_metric_scale(robot_prim) -> None:
    """Reject the unit-conversion transform that caused black Hawk images."""

    units_resolve_attribute = robot_prim.GetAttribute(
        "xformOp:scale:unitsResolve"
    )

    if not units_resolve_attribute:
        print("[checkpoint] Robot metric scale: none (correct)", flush=True)
        return

    scale_value = units_resolve_attribute.Get()

    if scale_value is None:
        print("[checkpoint] Robot metric scale: none (correct)", flush=True)
        return

    components = tuple(float(component) for component in scale_value)

    if not all(
        math.isclose(
            component,
            1.0,
            rel_tol=0.0,
            abs_tol=1e-9,
        )
        for component in components
    ):
        raise RuntimeError(
            "Nova Carter received an unexpected metric-conversion scale:\n"
            f"  xformOp:scale:unitsResolve = {components}\n\n"
            "The robot must remain meter-authored in this 1.0 m/unit stage; "
            "the scene was not saved."
        )

    print(
        f"[checkpoint] Robot metric scale: {components} (identity)",
        flush=True,
    )


def add_nova_carter(
    stage,
    simulation_app,
    stage_utils,
    UsdGeom,
    Gf,
):
    """Reference, place, and configure Nova Carter."""

    print("\nAdding Nova Carter:", flush=True)
    print(f"  Asset: {NOVA_CARTER_ASSET}", flush=True)
    print(f"  Prim:  {ROBOT_PRIM_PATH}", flush=True)
    print(f"  Pose:  {ROBOT_POSITION_METERS} m", flush=True)

    robot_prim = stage.DefinePrim(ROBOT_PRIM_PATH, "Xform")

    # Author placement before adding the reference. Nova Carter's referenced
    # root contains composed transform metadata; changing it afterward through
    # XformCommonAPI caused the earlier script to fail during composition.
    placement_op = UsdGeom.Xformable(robot_prim).AddTranslateOp(
        precision=UsdGeom.XformOp.PrecisionDouble,
        opSuffix="scriptPlacement",
    )
    placement_op.Set(Gf.Vec3d(*ROBOT_POSITION_METERS))

    if not robot_prim.GetReferences().AddReference(NOVA_CARTER_ASSET):
        raise RuntimeError("Could not add the Nova Carter USD reference.")

    first_load_updates = wait_for_stage_loading(
        simulation_app,
        stage_utils,
        settle_updates=30,
    )

    robot_prim = stage.GetPrimAtPath(ROBOT_PRIM_PATH)

    if not robot_prim.IsValid():
        raise RuntimeError("Nova Carter did not compose at /World/Robot.")

    print(
        f"[checkpoint] Nova Carter referenced in "
        f"{first_load_updates} update(s).",
        flush=True,
    )

    print("\nSelecting Nova Carter variants:", flush=True)
    for set_name, choice in ROBOT_VARIANTS.items():
        select_variant(stage, set_name, choice)
        wait_for_stage_loading(
            simulation_app,
            stage_utils,
            settle_updates=15,
        )

    robot_prim = stage.GetPrimAtPath(ROBOT_PRIM_PATH)
    validate_robot_has_no_metric_scale(robot_prim)
    return robot_prim


def validate_robot_and_camera(stage, UsdGeom) -> None:
    """Validate the final variant selections and front-left Hawk camera."""

    robot_prim = stage.GetPrimAtPath(ROBOT_PRIM_PATH)

    if not robot_prim.IsValid():
        raise RuntimeError("Nova Carter is missing during final validation.")

    for set_name, expected_choice in ROBOT_VARIANTS.items():
        selected_choice = (
            robot_prim
            .GetVariantSets()
            .GetVariantSet(set_name)
            .GetVariantSelection()
        )

        if selected_choice != expected_choice:
            raise RuntimeError(
                f"Final variant mismatch: {set_name}={selected_choice!r}; "
                f"expected {expected_choice!r}."
            )

    camera_prim = stage.GetPrimAtPath(FRONT_LEFT_HAWK_CAMERA_PATH)

    if not camera_prim.IsValid() or not camera_prim.IsA(UsdGeom.Camera):
        raise RuntimeError(
            "The front-left Hawk camera was not composed:\n"
            f"  {FRONT_LEFT_HAWK_CAMERA_PATH}\n\n"
            "Confirm that the Sensors variant is All_Sensors."
        )

    print("[checkpoint] All robot variants verified.", flush=True)
    print("[checkpoint] Front-left Hawk camera found.", flush=True)


def save_robot_scene(stage) -> None:
    """Export the edited root layer without overwriting the base scene."""

    OUTPUT_SCENE_PATH.parent.mkdir(parents=True, exist_ok=True)

    if not stage.GetRootLayer().Export(str(OUTPUT_SCENE_PATH)):
        raise RuntimeError(
            "USD could not export the completed robot scene:\n"
            f"  {OUTPUT_SCENE_PATH}"
        )

    if not OUTPUT_SCENE_PATH.is_file():
        raise RuntimeError(
            "USD reported a successful export, but the output file "
            f"does not exist:\n  {OUTPUT_SCENE_PATH}"
        )

    print(f"[checkpoint] Saved: {OUTPUT_SCENE_PATH}", flush=True)


def set_initial_view(simulation_app, ViewportManager) -> None:
    """Set the GUI Perspective camera without changing robot sensors."""

    ViewportManager.set_camera(VIEWPORT_CAMERA_PATH)

    viewport_camera = ViewportManager.get_camera()
    ViewportManager.set_camera_view(
        camera=viewport_camera,
        eye=INITIAL_VIEW_EYE,
        target=INITIAL_VIEW_TARGET,
    )

    # Render a few updates so the requested view is visible before entering
    # the interactive inspection loop.
    for _ in range(3):
        simulation_app.update()

    print("[checkpoint] Initial Perspective view configured.", flush=True)
    print(f"  Eye:    {INITIAL_VIEW_EYE}", flush=True)
    print(f"  Target: {INITIAL_VIEW_TARGET}", flush=True)


# -----------------------------------------------------------------------------
# Application entry point
# -----------------------------------------------------------------------------

def main() -> None:
    """Create, validate, save, and display the robot restaurant scene."""

    # SimulationApp must exist before importing Omniverse or pxr modules.
    from isaacsim.simulation_app import SimulationApp

    simulation_app = SimulationApp(
        {
            "headless": False,
            "renderer": "RayTracedLighting",
            "width": 1280,
            "height": 720,
        }
    )

    print("[checkpoint] SimulationApp created.", flush=True)

    try:
        import isaacsim.core.experimental.utils.stage as stage_utils
        from isaacsim.core.rendering_manager import ViewportManager
        from pxr import Gf, UsdGeom

        print("\n" + "=" * 72, flush=True)
        print("CREATING METER-SCALE RESTAURANT ROBOT SCENE", flush=True)
        print("=" * 72, flush=True)

        stage = open_and_validate_restaurant(
            simulation_app,
            stage_utils,
            UsdGeom,
        )

        add_nova_carter(
            stage,
            simulation_app,
            stage_utils,
            UsdGeom,
            Gf,
        )

        wait_for_stage_loading(
            simulation_app,
            stage_utils,
            settle_updates=60,
        )

        validate_robot_and_camera(stage, UsdGeom)
        set_initial_view(simulation_app, ViewportManager)
        save_robot_scene(stage)

        print("\n" + "=" * 72, flush=True)
        print("SCENE CREATED SUCCESSFULLY", flush=True)
        print("=" * 72, flush=True)
        print(f"Stage units:    {EXPECTED_METERS_PER_UNIT} m/unit", flush=True)
        print(f"Robot position: {ROBOT_POSITION_METERS} m", flush=True)
        print("Robot rotation: (0.0, 0.0, 0.0) degrees", flush=True)
        print("Robot scale:    (1.0, 1.0, 1.0)", flush=True)
        print(f"Saved to:       {OUTPUT_SCENE_PATH}", flush=True)
        print("\nPress Play to let Nova Carter settle onto the floor.", flush=True)
        print("Close Isaac Sim when finished.", flush=True)

        # During the interactive phase, is_running() becomes false when the
        # Isaac Sim window is closed. Ctrl+C is handled below as a backup.
        while simulation_app.is_running():
            simulation_app.update()

    except KeyboardInterrupt:
        print("\nShutdown requested from the terminal.", flush=True)
    except BaseException:
        # Print while Kit is alive so SimulationApp.close() cannot hide the
        # useful traceback behind its normal shutdown messages.
        print("\n" + "=" * 72, flush=True)
        print("ERROR WHILE CREATING THE ROBOT SCENE", flush=True)
        print("=" * 72, flush=True)
        traceback.print_exc()
        raise
    finally:
        if "simulation_app" in locals() and not simulation_app.is_exiting():
            simulation_app.close()


if __name__ == "__main__":
    main()